#ifndef CEE_V0_LITE_TYPES_H
#define CEE_V0_LITE_TYPES_H

#include "CeeV0LiteMath.h"

namespace CeeV0Lite
{

enum MomentumMode
{
  kAutoMomentum = 0,
  kTofMomentum = 1,
  kTrackingMomentum = 2
};

enum HypothesisMask
{
  kPionHypothesis = 1u << 0,
  kProtonHypothesis = 1u << 1
};

enum CandidateType
{
  kK0Short = 310,
  kLambda = 3122,
  kAntiLambda = -3122
};

struct TrackInput
{
  TrackInput();

  int id;
  Vec3 positionCm;
  Vec3 direction;
  Mat3 positionCovarianceCm2;
  double sigmaDirectionRad;
  // CEE zero-field Lambda role assignment: proton DCA <= boundary,
  // pion DCA > boundary. Keep this per track so TPC/MWDC can differ.
  double lambdaRoleDcaBoundaryCm;

  bool hasTrackingMomentum;
  Vec3 trackingMomentumGeV;
  bool hasTrackingCovariance;
  Mat6 trackingCovariance;

  bool chargeKnown;
  int charge;

  bool hasTof;
  Vec3 tofPositionCm;
  double tofTimeNs;
  double sigmaTofTimeNs;
  double sigmaPathLengthCm;

  unsigned int hypothesisMask;
  double qualityChi2;
  int qualityNdf;
};

struct PrimaryVertex
{
  PrimaryVertex();

  Vec3 positionCm;
  Mat3 covarianceCm2;
  double chi2;
  int nContributors;
};

struct EventInput
{
  EventInput();

  PrimaryVertex primaryVertex;
  // Time origin of the collision.  The default is ideal simulation timing:
  // generator t=0 with no T0-detector uncertainty.  Real data must set both
  // fields explicitly from its calibrated T0 measurement.
  double startTimeNs;
  double sigmaStartTimeNs;
};

struct TrackState
{
  TrackState();

  int id;
  int pdg;
  int charge;
  double massGeV;
  Vec3 positionCm;
  Vec3 momentumGeV;
  Mat6 covariance;
};

enum MotherCovarianceStatus
{
  kMotherCovarianceNotCalculated = 0,
  kMotherCovarianceValid,
  kMotherCovarianceVertexUpdateFailed,
  kMotherCovarianceNumericalPropagationFailed,
  kMotherCovarianceSharedTimeDerivativeFailed,
  kMotherCovarianceNonFinite,
  kMotherCovarianceNotPositiveSemidefinite,
  kMotherCovarianceProcessNoiseUnsupported,
  // The nominal mother fit succeeded, but at least one of the 24 central-
  // difference refits used to build the 7x12 outer Jacobian failed.  This is
  // kept distinct from malformed inputs and an invalid propagated matrix so
  // analysis can retain the central candidate for QA without claiming a
  // valid mother covariance.
  kMotherCovarianceJacobianPerturbationFailed
};

// Compact analogue of the KFParticle mother state.  The covariance ordering
// is fixed to (x, y, z, px, py, pz, E); daughter correlations generated by
// the common decay-vertex update are folded into this one matrix.
struct MotherState
{
  MotherState();

  Vec3 positionCm;
  Vec3 momentumGeV;
  double energyGeV;
  Mat7 covariance;
  bool covarianceValid;
  MotherCovarianceStatus covarianceStatus;
  // Diagnostics for the 12 Jacobian columns x two perturbation sides.
  // failedColumn uses the input order
  // (x1,y1,z1,px1,py1,pz1,x2,y2,z2,px2,py2,pz2); failedSide is +1 or -1.
  int jacobianFitsAttempted;
  int jacobianFitsSucceeded;
  int jacobianFailureCount;
  unsigned int jacobianPlusFailureMask;
  unsigned int jacobianMinusFailureMask;
  int jacobianFailedColumn;
  int jacobianFailedSide;
  // Integer value of VertexFitStatus for the first failed perturbation.
  int jacobianFirstFailureFitStatus;
};

struct TofMomentumEstimate
{
  TofMomentumEstimate();

  bool valid;
  double beta;
  double momentumGeV;
  double sigmaMomentumGeV;
  double pathLengthCm;
  double flightTimeNs;
};

enum ProductionFitStatus
{
  kProductionNotRun = 0,
  kProductionValid,
  kProductionDisabled,
  kProductionInvalidMother,
  kProductionPvResponseFailed,
  kProductionInvalidJointCovariance,
  kProductionSingularConstraint,
  kProductionNotConverged,
  kProductionUnphysicalState,
  kProductionUnsupportedCharge,
  kProductionInvalidConfiguration,
  kProductionMissingMagneticField,
  kProductionFlightRangeExceeded
};

enum ProductionCorrelationModel
{
  kProductionUserSuppliedJointCovariance = 0,
  kProductionTrackingIndependentPv,
  kProductionTofPvResponse
};

// A separate constrained copy. Candidate::mother remains the original 7D fit.
// S always describes the full signed production->decay interval; changing
// endpoints does not change S. Charge is in units of e, momentum is physical
// GeV/c (not rigidity). The uniform By used for the fit travels with the state.
struct ProductionState
{
  ProductionState();
  bool valid;
  ProductionFitStatus status;
  ProductionCorrelationModel correlationModel;
  bool atProductionVertex;
  int iterations;
  int charge;
  double magneticFieldByTesla;
  Vec3 positionCm;
  Vec3 momentumGeV;
  double energyGeV;
  double flightParameterS;
  Mat8 covariance;
  double pvConstraintChi2;
  int pvConstraintNdf;
  double totalChi2;
  int totalNdf;
};

struct FlightObservables
{
  FlightObservables();
  bool valid;
  double massGeV;
  double sigmaMassGeV;
  double decayLengthCm;       // signed S*|p|, not the old Euclidean length
  double sigmaDecayLengthCm;
  double ctauCm;              // S*m, not ns and not the input PDG lifetime
  double sigmaCtauCm;
};

struct Candidate
{
  Candidate();

  CandidateType type;
  int daughterId[2];
  int daughterPdg[2];
  TrackState daughterAtVertex[2];

  MotherState mother;

  // v0.6.3: auxiliary PV-constrained state, not used by legacy cuts.
  ProductionState motherTopo;
  FlightObservables topoFlight;

  Vec3 decayVertexCm;
  Mat3 decayVertexCovarianceCm2;
  Vec3 momentumGeV;

  double massGeV;
  double sigmaMassGeV;
  double daughterDcaCm;
  double geometricChi2;
  int geometricNdf;
  double geometricChi2Ndf;
  // STAR-like total after adding the two effective production-vertex
  // constraints to the two-daughter geometric fit:
  //   (chi2_geometric + chi2_PV_constraint) / (ndf_geometric + 2).
  double topologicalChi2Ndf;
  double topologicalChi2;
  int topologicalNdf;
  // Pure production-vertex residual retained separately for QA.  This is the
  // quantity that older CeeV0Lite versions exposed as topologicalChi2Ndf.
  double primaryVertexConstraintChi2;
  int primaryVertexConstraintNdf;
  double primaryVertexConstraintChi2Ndf;
  double decayLengthCm;
  double sigmaDecayLengthCm;
  double decayLengthSignificance;
  double pointingCosine;
  double daughterDcaToPvCm[2];
  // KFParticle::GetDeviationFromVertex returns the raw chi2 quadratic form,
  // despite its historical name.  Store that convention as the cut variable
  // and retain sqrt(chi2) explicitly as a significance-like QA observable.
  double daughterChi2FromPv[2];
  double daughterPvSignificance[2];
  // Deprecated 0.5.x compatibility alias.  It remains sqrt(chi2); new cuts
  // and analysis code should use daughterChi2FromPv explicitly.
  double daughterDeviationFromPv[2];

  double decayTimeNs;
  int tofIterations;
  bool tofConverged;
  // A candidate in the output always has a valid central fit.  This flag says
  // whether all 12 columns x two sides needed by the outer numerical
  // Jacobian also fitted successfully.
  bool motherJacobianComplete;
  // False for a retained Jacobian-failure QA row.  In that case sigmaMass,
  // vertex/length errors, L/sigmaL and PV/topological chi2 are NaN and their
  // cuts were deliberately not evaluated.
  bool covarianceDependentCutsEvaluated;
};

TofMomentumEstimate EstimateTofMomentum(double massGeV,
                                        double pathLengthCm,
                                        double flightTimeNs,
                                        double sigmaPathLengthCm,
                                        double sigmaFlightTimeNs,
                                        double maximumBeta = 0.9995);

Mat6 BuildTofStateCovariance(const TrackInput& track,
                             const Vec3& unitDirection,
                             double momentumGeV,
                             double sigmaMomentumGeV);

// Calculate M and sigma(M) from the mother (px,py,pz,E) covariance block,
// matching the way KFParticle::GetMass consumes the already-built mother.
bool MotherMassAndError(const MotherState& mother,
                        double& massGeV,
                        double& sigmaMassGeV,
                        double roundoffToleranceMultiplier = 64.);

// Add one common scalar nuisance parameter, e.g. the event T0, exactly once:
// C <- C + (dy/da) sigma_a^2 (dy/da)^T.
bool AddCommonNuisanceCovariance(MotherState& mother,
                                 const double derivative[7],
                                 double variance);

} // namespace CeeV0Lite

#endif
